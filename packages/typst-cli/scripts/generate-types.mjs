// Writes index.d.ts from @jsfi/typst-wasm's declarations, so that the two packages declare one API:
// everything up to the module's loader is copied as it is, and the loader is replaced by this
// package's `init()` and `initSync()`, which select the CLI instead. build.sh runs it after every
// build; commit index.d.ts whenever it changes.
//
//   node packages/typst-cli/scripts/generate-types.mjs [path/to/typst_wasm.d.ts]

import { readFileSync, writeFileSync } from 'node:fs';

/** Where the module's loader starts in wasm-bindgen's declarations. */
const LOADER = '\nexport type InitInput =';

const HEADER = `// Generated by scripts/generate-types.mjs from @jsfi/typst-wasm's declarations; do not edit.
// The API is declared in the module's Rust sources; init() and initSync() below in the script.
`;

const INIT = `
export interface InitOptions {
    /**
     * The typst executable to run. Defaults to \`typst\` on the PATH. The README's version table
     * names the versions it can be.
     */
    typstPath?: string;
    /**
     * Whether to leave out the fonts embedded in the typst executable, Typst's defaults, so that
     * only fonts given to \`addFont\` are used, as in @jsfi/typst-wasm. Defaults to \`false\`.
     */
    ignoreEmbeddedFonts?: boolean;
}

export interface Cli {
    /** The absolute path of the executable every \`Compiler\` runs, as found on the PATH. */
    path: string;
    /** Its version, such as "0.15.1". */
    version: string;
}

/**
 * Finds the typst CLI, checks its version and makes it the one every \`Compiler\` created afterwards
 * runs, with the given font settings. Throws if it cannot be run or is too old.
 */
export function initSync(options?: InitOptions): Cli;

/** \`initSync()\` as a promise. */
export default function init(options?: InitOptions): Promise<Cli>;
`;

/** Index.d.ts for the module's declarations `wasm`. */
function generateTypes(wasm) {
	const loader = wasm.indexOf(LOADER);
	if (loader < 0) {
		throw new Error(`@jsfi/typst-wasm's declarations no longer contain "${LOADER.trim()}".`);
	}
	const api = wasm
		.slice(0, loader)
		.replace(/^\/\* tslint:disable \*\/\n\/\* eslint-disable \*\/\n/, '')
		.trim();
	return `${HEADER}\n${api}\n${INIT}`;
}

// The declarations given as argument, or those of the installed @jsfi/typst-wasm.
const declarations = readFileSync(
	process.argv[2] ??
		new URL('typst_wasm.d.ts', import.meta.resolve('@jsfi/typst-wasm/package.json')),
	'utf8',
);
writeFileSync(new URL('../index.d.ts', import.meta.url), generateTypes(declarations));
